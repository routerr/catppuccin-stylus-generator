export function translate(language: AppLanguage, key: TranslationKey, vars?: Record<string, string | number>): string {
  const template = TRANSLATIONS[language][key] ?? EN[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, variable: string) => String(vars[variable] ?? `{${variable}}`));
}
